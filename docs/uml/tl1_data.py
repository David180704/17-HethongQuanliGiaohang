DONE_SPRINTS = {1, 2, 3}


def status_of(stories):
    sprints = [SPRINT_OF[s] for s in stories]
    last = max(sprints)
    if all(s in DONE_SPRINTS for s in sprints):
        return f"Đã làm (Sprint {last})"
    if any(s in DONE_SPRINTS for s in sprints):
        return f"Một phần đã làm; hoàn thiện Sprint {last}"
    return f"Kế hoạch Sprint {last}"


def alt(after, guard, steps, then="end", lane=H, else_guard="ngược lại"):
    return dict(after=after, guard=guard, steps=steps, then=then, lane=lane, else_guard=else_guard)


def uc(code, name, pkg, actors, secondary, stories, de, summary, pre, post, lanes, main, alts=(), ui=None):
    return dict(code=code, name=name, pkg=pkg, actors=actors, secondary=secondary, stories=stories, de=de,
                status=status_of(stories), summary=summary, pre=pre, post=post, lanes=lanes, main=main,
                alts=list(alts), ui=ui)


